#!/usr/bin/env python3
"""Generate browser vectors and native icon masks from the selected Bend artwork."""
import argparse
import io
import json
import re
from pathlib import Path
import subprocess
import tempfile
import xml.etree.ElementTree as ET

import cairosvg
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
GAME = ROOT / 'examples' / 'survivors'
ET.register_namespace('', 'http://www.w3.org/2000/svg')


def sheet(name):
    with tempfile.TemporaryDirectory(prefix='nightfall-icon-export-') as directory:
        source, binary = Path(directory) / 'icons.c', Path(directory) / 'icons'
        subprocess.run(['bend', str(HERE / name), '-o', str(source)], check=True, capture_output=True)
        subprocess.run(['clang', '-O0', str(source), '-o', str(binary), '-lm', '-lpthread'], check=True, capture_output=True)
        return ET.fromstring(subprocess.check_output([str(binary)], text=True))


def body(group):
    return ''.join(ET.tostring(child, encoding='unicode').replace(' xmlns="http://www.w3.org/2000/svg"', '') for child in group)


def native_rows(svg):
    image = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode(), output_width=20, output_height=20))).convert('RGBA')
    palette = [tuple(bytes.fromhex(color[1:])) for color in sorted(set(re.findall(r'#[0-9a-fA-F]{6}', svg)))]
    grid = [[None] * 20 for _ in range(20)]
    for y in range(20):
        for x in range(20):
            r, g, b, alpha = image.getpixel((x, y))
            if alpha >= 128:
                color = min(palette, key=lambda c: (c[0]-r)**2 + (c[1]-g)**2 + (c[2]-b)**2)
                grid[y][x] = (color[0] << 16) | (color[1] << 8) | color[2]
    rows, previous = [], {}
    for y in range(20):
        x, current = 0, {}
        while x < 20:
            color = grid[y][x]
            if color is None:
                x += 1
                continue
            start = x
            while x < 20 and grid[y][x] == color:
                x += 1
            key = (start, x-start, color)
            rectangle = previous.get(key)
            if rectangle is None:
                rectangle = [start, y, x-start, 0, color]
                rows.append(rectangle)
            rectangle[3] += 1
            current[key] = rectangle
        previous = current
    return rows


def generate():
    icons = {'weapon': [body(group) for group in sheet('weapon-artwork.bend')], 'passive': [body(group) for group in sheet('pool-artwork.bend')], 'personal': []}
    for group in sheet('artwork.bend'):
        if group.attrib['data-kind'] == '0' and group.attrib['data-style'] == '0':
            assert int(group.attrib['data-hero']) == len(icons['personal'])
            icons['personal'].append(body(group))
    assert [len(icons[kind]) for kind in icons] == [24, 18, 7]
    browser = '// Generated by tools/icon-lab/game-build.py. Edit the Bend artwork.\nexport const ITEM_ICON_SHAPES = ' + json.dumps(icons, ensure_ascii=False, indent=2) + ' as const\n'
    characters = json.loads((HERE / 'study-matrix.json').read_text())['characters']
    labels = [f"{hero['trinket']} · {hero['innate']}. {hero['innateTooltip']}" for hero in characters]
    browser += 'export const PERSONAL_ICON_LABELS = ' + json.dumps(labels, ensure_ascii=False) + ' as const\n'
    browser = subprocess.run([str(ROOT / 'node_modules' / '.bin' / 'dprint'), 'fmt', '--stdin', 'item-icon-shapes.mts'], input=browser, text=True, check=True, capture_output=True, cwd=ROOT).stdout
    native = ['# Generated by tools/icon-lab/game-build.py. Edit the Bend artwork.', 'import Base', 'import native_draw.bend as D', '', 'def icon(kind: U32,id: U32,+x: F32,+y: F32,+size: F32,tail: List<&2,D.Rect>) -> List<&2,D.Rect>:', '  match kind id:']
    helpers = []
    for category, (kind, shapes) in enumerate(icons.items()):
        for ident, shape in enumerate(shapes):
            name = f'{kind}_{ident}'
            native.append(f'    case {category} {ident}: {name}(x,y,size,tail)')
            svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">' + shape + '</svg>'
            rows = native_rows(svg)
            helpers.extend(['', f'def {name}(+x: F32,+y: F32,+size: F32,tail: List<&2,D.Rect>) -> List<&2,D.Rect>:'])
            last = 'tail'
            for index, (px, py, width, height, color) in enumerate(rows):
                variable = f'r{index}'
                helpers.append(f'  {variable} = D.rect((x + {px / 20:.2f} * size : F32),(y + {py / 20:.2f} * size : F32),({width / 20:.2f} * size : F32),({height / 20:.2f} * size : F32),{color},{last})')
                last = variable
            helpers.append('  ' + last)
    native.append('    case _ _: tail')
    native = native[:4] + helpers + ['', *native[4:], '']
    return {GAME / 'item-icon-shapes.mts': browser, GAME / 'native_icons.bend': '\n'.join(native)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            assert path.read_text() == content, f'Stale generated icon source: {path}'
        else:
            path.write_text(content)
        print(f'{"Checked" if args.check else "Generated"} {path.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
