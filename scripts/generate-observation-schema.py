#!/usr/bin/env python3
"""Generate the network observation schema and host types from Bend Data declarations.

Only the reachable presentation types are exported. ECS state is not a host API.
Unsupported syntax fails generation rather than weakening the network boundary.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / 'examples/survivors'


def split(text):
    depth = 0
    start = 0
    result = []
    for index, char in enumerate(text):
        depth += char in '<('
        depth -= char in '>)'
        if char == ',' and depth == 0:
            result.append(text[start:index].strip())
            start = index + 1
    if text[start:].strip():
        result.append(text[start:].strip())
    return result


sources = {p.stem: p.read_text() for p in APP.glob('*.bend')}
imports = {owner: {alias: Path(path).stem for path, alias in
           re.findall(r'^import\s+(\S+)\s+as\s+(\w+)', text, re.M)}
           for owner, text in sources.items()}
declarations = {}
for owner, text in sources.items():
    for match in re.finditer(r'^type\s+(\w+)(?:<([^\n]*)>)?\s+is\s+Data:[ \t]*([^\n]*(?:\n[ \t]+[^\n]*)*)', text, re.M):
        name, generic, body = match.groups()
        parameters = [p.split(':')[0].strip().lstrip('-+~') for p in split(generic or '')]
        variants = {}
        for tag, members in re.findall(r'(\w+)\{([^{}]*)\}', body):
            variants[tag] = [tuple(part.split(':', 1)) for part in split(members)]
        declarations[owner, name] = (parameters, variants)

graph = {}


def resolve(text, owner, bindings=None):
    bindings = bindings or {}
    text = text.strip()
    if text in bindings:
        return bindings[text]
    primitives = {'U32': 'u32', 'F32': 'f32', 'Bool': 'bool', 'String': 'string', 'Nat': 'nat'}
    if text in primitives:
        return primitives[text]
    match = re.fullmatch(r'([\w.]+)(?:<(.*)>)?', text)
    if not match:
        raise ValueError(f'{owner}: unsupported observation type {text!r}')
    name, args = match.groups()
    arguments = [resolve(arg, owner, bindings) for arg in split(args or '') if not arg.startswith('&')]
    if name in ('List', 'Maybe'):
        if len(arguments) != 1:
            raise ValueError(f'Invalid {name}: {text}')
        if name == 'List':
            return {'list': arguments[0]}
        key = 'Maybe' + re.sub(r'\W', '', json.dumps(arguments, sort_keys=True))
        graph[key] = {'None': [], 'Some': [['value', arguments[0]]]}
        return {'ref': key}
    if '.' in name:
        alias, name = name.split('.', 1)
        owner = imports[owner][alias]
    key = ''.join(word.capitalize() for word in owner.split('-')) + name
    if arguments:
        key += re.sub(r'\W', '', json.dumps(arguments, sort_keys=True))
    if key not in graph:
        parameters, variants = declarations[owner, name]
        if len(parameters) != len(arguments) or not variants:
            raise ValueError(f'Unsupported Data declaration: {owner}.{name}')
        graph[key] = {}  # Recursive indices refer back to this node.
        scope = dict(zip(parameters, arguments))
        graph[key] = {tag: [[field.strip(), resolve(type_, owner, scope)] for field, type_ in fields]
                      for tag, fields in variants.items()}
    return {'ref': key}


roots = {name: resolve(type_, owner) for name, type_, owner in [
    ('game', 'Observation', 'game'), ('core', 'Observation', 'coop-core'),
    ('journal', 'State', 'coop-hit-journal'), ('admission', 'State', 'coop-session'),
    ('receipt', 'Receipt', 'coop-session'),
]}

header = '// Generated by scripts/generate-observation-schema.py from Bend. Do not edit.\n'
(APP / 'observation-schema.generated.mts').write_text(
    header + 'import type { Schema } from "./observation-schema.mts";\nexport const roots = ' + json.dumps(roots, separators=(',', ':')) + ';\n' +
    'export const schema: Schema = ' + json.dumps(graph, sort_keys=True, separators=(',', ':')) + ';\n')
