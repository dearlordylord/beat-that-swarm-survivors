import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { survivorLayers } from '../examples/survivors/survivor-shapes.mjs';

// SVG nonzero fill sampled at pixel centers is exact for integer orthogonal art.
function pixels(path) {
  assert(!/[^MmhHvVzZ\d\s-]/.test(path), 'Only integer rectilinear paths are supported');
  const tokens = path.match(/[a-zA-Z]|-?\d+/g);
  const edges = [];
  let x = 0, y = 0, sx = 0, sy = 0;
  for (let i = 0; i < tokens.length;) {
    const command = tokens[i++];
    const ox = x, oy = y;
    switch (command) {
      case 'M': x = +tokens[i++]; y = +tokens[i++]; sx = x; sy = y; break;
      case 'm': x += +tokens[i++]; y += +tokens[i++]; sx = x; sy = y; break;
      case 'H': x = +tokens[i++]; break;
      case 'h': x += +tokens[i++]; break;
      case 'V': y = +tokens[i++]; break;
      case 'v': y += +tokens[i++]; break;
      case 'z': case 'Z': x = sx; y = sy; break;
      default: throw Error(`Unsupported path command: ${command}`);
    }
    assert(Number.isInteger(x) && Number.isInteger(y) && x >= 0 && x <= 32 && y >= 0 && y <= 40);
    if (command !== 'M' && command !== 'm' && oy !== y) edges.push([x, oy, y]);
  }
  return Array.from({ length: 40 }, (_, py) => Array.from({ length: 32 }, (_, px) =>
    edges.reduce((winding, [ex, y0, y1]) => winding + (ex > px + .5
      ? y0 <= py + .5 && y1 > py + .5 ? 1 : y1 <= py + .5 && y0 > py + .5 ? -1 : 0
      : 0), 0) !== 0));
}

function rectangles(mask) {
  const result = [];
  let previous = new Map();
  for (let y = 0; y < 40; y++) {
    const current = new Map();
    for (let x = 0; x < 32;) {
      if (!mask[y][x]) { x++; continue; }
      const start = x;
      while (x < 32 && mask[y][x]) x++;
      const key = `${start}:${x}`;
      const rect = previous.get(key) || [start, y, x - start, 0];
      if (!previous.has(key)) result.push(rect);
      rect[3]++;
      current.set(key, rect);
    }
    previous = current;
  }
  // Check the conversion before writing generated source.
  const restored = Array.from({ length: 40 }, () => Array(32).fill(false));
  for (const [x, y, w, h] of result) for (let j = y; j < y + h; j++) for (let i = x; i < x + w; i++) restored[j][i] = true;
  assert.deepEqual(restored, mask);
  return result;
}

const float = n => n < 0 ? `(0.0 - ${-n}.0 : F32)` : `${n}.0`;
let output = `# Generated by node scripts/generate-native-survivor-art.mjs; edit survivor-shapes.mjs.
# SVG layer order becomes front-first display lists. Anchor: (16,37), scale: 0.75.
import Base
import native_draw.bend as D

def tint(on: Bool,yes: U32,no: U32) -> U32:
  match on:
    case True{}: yes
    case False{}: no

def box(+x: F32,+y: F32,dx: F32,dy: F32,w: F32,h: F32,color: U32,tail: List<&2,D.Rect>) -> List<&2,D.Rect>:
  D.rect((x + dx * 0.75 : F32),(y + dy * 0.75 : F32),(w * 0.75 : F32),(h * 0.75 : F32),color,tail)
`;
for (let id = 0; id < 8; id++) {
  output += `\ndef hero_${id}(+x: F32,+y: F32,+flash: Bool,tail: List<&2,D.Rect>) -> List<&2,D.Rect>:\n`;
  let count = 0;
  for (const [color, path] of survivorLayers(id)) {
    assert(/^#[0-9a-f]{6}$/i.test(color));
    const normal = parseInt(color.slice(1), 16);
    const flash = [16, 8, 0].reduce((value, shift) => value | Math.round((((normal >> shift) & 255) + 255) / 2) << shift, 0);
    for (const [x, y, w, h] of rectangles(pixels(path))) {
      const tail = count ? `r${count - 1}` : 'tail';
      output += `  r${count++} = box(x,y,${float(x - 16)},${float(y - 37)},${float(w)},${float(h)},tint(flash,${flash},${normal}),${tail})\n`;
    }
  }
  output += `  r${count - 1}\n`;
}
output += '\ndef player(character: U32,x: F32,y: F32,flash: Bool,tail: List<&2,D.Rect>) -> List<&2,D.Rect>:\n  match character:\n';
for (let id = 0; id < 8; id++) output += `    case ${id}: hero_${id}(x,y,flash,tail)\n`;
output += '    case _: hero_0(x,y,flash,tail)\n';
const target = new URL('../examples/survivors/native_survivors.bend', import.meta.url);
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), output, 'Native survivor art is stale; run this generator');
else await writeFile(target, output);
console.log('Native survivor rectangles match all eight SVG layer masks.');
