#!/usr/bin/env node
// Development fixture: actual emitted Bend sound policy + solo frame encoder;
// the browser adapter's synthesis callback is the only replaced side effect.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
const directory=resolve(process.argv[2]);
const url=name=>pathToFileURL(join(directory,name+'.mjs')).href;
const [{default:S},{default:GE},{default:G}]=await Promise.all(['audio-events','game-encoder','game'].map(name=>import(url(name))));
const list=rows=>rows.reduceRight((tail,head)=>({$:'Con',head,tail}),{$:'Nil'});
const array=rows=>{const result=[];for(;rows.$==='Con';rows=rows.tail)result.push(rows.head);return result;};
const identity=(slot=1,lifetime='first')=>({$:'Identity',slot,lifetime});
const enemy=(health=10,life='first',archetype=2)=>({$:'Enemy',identity:identity(1,life),archetype,health,x:0});
const friendly=(radius=2,life='first',weapon=3)=>({$:'FriendlyProjectile',identity:identity(2,life),weapon,radius,x:100});
const hostile=()=>({$:'HostileProjectile',identity:identity(3),weapon:1,x:-100});
const meta=(tick=1,extra={})=>({$:'Meta',run:'fixture',tick,phase:0,round:0,hp:100,kills:0,gold:0,xp:0,level:1,px:0,confirmed:false,...extra});
const codes=result=>array(result.events).map(e=>e.kind);
assert.equal(S.same(enemy(),enemy(9)),true);
assert.equal(S.same(enemy(),enemy(10,'second')),false);
assert.equal(S.same(enemy(),enemy(10,'first',4)),false);
assert.equal(S.same(friendly(),friendly(2,'first',4)),false);
assert.equal(S.same(friendly(),{...hostile(),identity:identity(2),weapon:3}),false);
assert.deepEqual(codes(S.baseline(meta(),list([friendly(),hostile()]))),[]);
const initial=S.observe(S.fresh(),meta(),list([enemy()])).state;
assert.deepEqual(codes(S.observe(initial,meta(2),list([friendly(),enemy(8),hostile()]))),[0,1,6]);
assert.deepEqual(codes(S.observe(initial,meta(2,{confirmed:true}),list([enemy(8)]))),[]);
assert.deepEqual(codes(S.observe(initial,meta(1),list([friendly()]))),[]);
assert.deepEqual(codes(S.observe(initial,meta(0),list([friendly()]))),[]);
assert.deepEqual(codes(S.observe(initial,meta(2,{run:'other'}),list([friendly()]))),[]);
const flight=S.baseline(meta(),list([friendly()])).state;
assert.deepEqual(codes(S.observe(flight,meta(2),list([friendly(4)]))),[8]);
assert.deepEqual(codes(S.observe(flight,meta(2),list([friendly(3.99)]))),[]);
assert.deepEqual(codes(S.observe(flight,meta(2),list([friendly(4,'second')]))),[0]);
assert.deepEqual(codes(S.observe(S.baseline(meta(),list([friendly(0)])).state,meta(2),list([friendly(4)]))),[]);
const impactState=S.observe(initial,meta(3,{confirmed:true}),list([enemy(8)])).state;
const impact=S.impacts(impactState,list([{$:'Impact',tick:2,x:0},{$:'Impact',tick:3,x:100},{$:'Impact',tick:4,x:200}]));
assert.deepEqual(codes(impact),[1]);assert.equal(impact.state.impactTick,3);assert.deepEqual(codes(S.impacts(impact.state,list([{$:'Impact',tick:3,x:100}]))),[]);
// Use a real solo Run, real encoder and the browser producer. No Body DTO exists.
const packet=G.start_seed(0,0,12345);assert.equal(packet.$,'Packet');
const typedEnemy={$:'State',spatial:{$:'Spatial',x:7200,y:7200,age:10,radius:8},archetype:1,identity:7,vitals:{$:'Vitals',health:10,maximum:10},status:{$:'Status',slow:{$:'Slow',ticks:0,frozen:false},burn:{$:'Burn',ticks:0,sourcePlayer:{$:'None'}}}};
const encode=(tick,age,health=10)=>JSON.parse(GE.encode({$:'Observation',run:{...packet.state.run,session:{...packet.state.run.session,tick}},offers:list([]),enemies:list([{...typedEnemy,spatial:{...typedEnemy.spatial,age},vitals:{...typedEnemy.vitals,health}}]),order:list([{$:'EnemyRef',identity:7}]),projectiles:list([]),pickups:list([])}));
const frame=encode(5,10);assert.equal(frame.enemies[0].lifetime,'enemy:7:0');assert.equal(encode(20,10).enemies[0].lifetime,'enemy:7:10');
let source=await readFile(new URL('./audio.mjs',import.meta.url),'utf8');
source=source.replace('"./dist/game.mjs"',JSON.stringify(url('game'))).replace('"./dist/audio-events.mjs"',JSON.stringify(url('audio-events')));
const {AudioEngine}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const engine=new AudioEngine(),events=[];engine.event=(name,pan)=>events.push({name,pan});
engine.observe(frame);assert.deepEqual(events,[]);
engine.observe(encode(6,11,8));assert.deepEqual(events.map(e=>e.name),['impact']);
assert.throws(()=>engine.observe({...encode(7,12),enemies:[{...frame.enemies[0],lifetime:undefined}]}),/explicit lifetime/);
const shotFrame={...encode(8,13),enemies:[],projectiles:[{identity:2,lifetime:'shot:2:8',hostile:false,weapon:4,radius:2,x:7200},{identity:3,lifetime:'shot:3:8',hostile:true,weapon:0,x:7200}],actorOrder:[{projectile:3},{projectile:2}]};
engine.observe(shotFrame);assert.deepEqual(events.slice(-2).map(e=>e.name),['hostile','shot']);
assert.equal(engine.soundState.subjects.$!=='Empty',true);
console.log('PASS typed audio subjects: identity, order, baseline, damage, radius growth, confirmed impacts, actual solo encoder producer and strict lifetimes');
