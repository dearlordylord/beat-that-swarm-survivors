export function prototypeLayers(id, variant = 0) {
  const index = Number.isInteger(id) && id >= 0 && id < 8 ? id : 0;
  return variant === 1 ? prototypes[index] : survivorLayers(index);
}

export function prototypeSvg(id, variant = 0) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 40" shape-rendering="crispEdges">${prototypeLayers(id, variant).map(([color, path]) => `<path fill="${color}" d="${path}"/>`).join('')}</svg>`;
}
